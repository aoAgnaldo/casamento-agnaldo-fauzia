alter table public.protocols add column if not exists session_token uuid;
alter table public.protocols add column if not exists session_expires_at timestamptz;

create or replace function public.verify_protocol(p_access_code text,p_pin text)
returns table(id uuid,full_name text,session_token uuid)
language plpgsql security definer set search_path=public,extensions as $$
declare v_id uuid; v_name text; v_token uuid;
begin
 select p.id,p.full_name into v_id,v_name from protocols p where p.active=true and p.access_code=upper(trim(p_access_code)) and p.pin_hash=crypt(p_pin,p.pin_hash) limit 1;
 if v_id is null then return; end if;
 v_token:=gen_random_uuid(); update protocols set session_token=v_token,session_expires_at=now()+interval '12 hours' where id=v_id;
 return query select v_id,v_name,v_token;
end $$;
grant execute on function public.verify_protocol(text,text) to anon,authenticated;

create or replace function public.protocol_checkin_list(p_token uuid)
returns table(id uuid,code text,full_name text,whatsapp text,allowed_guests integer,rsvp_status text,companion_count integer,checked_in boolean,checked_in_at timestamptz,table_id bigint,table_name text,table_capacity integer)
language sql security definer set search_path=public as $$
