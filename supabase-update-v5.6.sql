create or replace function public.protocol_check_in(p_token uuid,p_invitation_id uuid)
returns void language plpgsql security definer set search_path=public as $$
begin
 if not exists(select 1 from protocols p where p.session_token=p_token and p.session_expires_at>now() and p.active=true) then raise exception 'Sessão da recepção expirada'; end if;
 update invitations set checked_in=true,checked_in_at=now() where id=p_invitation_id;
end $$;
grant execute on function public.protocol_check_in(uuid,uuid) to anon,authenticated;

