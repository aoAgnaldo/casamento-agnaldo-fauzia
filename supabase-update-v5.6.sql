create table if not exists public.reception_tables (
 id bigint generated by default as identity primary key,
 name text not null unique,
 capacity integer not null check (capacity > 0 and capacity <= 100),
 description text,
 created_at timestamptz not null default now()
);

alter table public.invitations add column if not exists table_id bigint references public.reception_tables(id) on delete set null;

create table if not exists public.protocols (
 id uuid primary key default gen_random_uuid(),
 full_name text not null,
 whatsapp text,
 access_code text not null unique,
 pin_hash text not null,
 active boolean not null default true,
 created_at timestamptz not null default now()
);

alter table public.reception_tables enable row level security;
alter table public.protocols enable row level security;

revoke all on public.reception_tables from anon, authenticated;
revoke all on public.protocols from anon, authenticated;
grant execute on function public.is_admin() to authenticated;

create or replace function public.admin_list_tables()
returns table(id bigint,name text,capacity integer,description text,used_seats bigint,guests jsonb)
language sql security definer set search_path=public
as $$
 select t.id,t.name,t.capacity,t.description,
        count(i.id) filter (where i.rsvp_status='confirmed')::bigint as used_seats,
        coalesce(jsonb_agg(jsonb_build_object('id',i.id,'full_name',i.full_name,'code',i.code,'companion_count',i.companion_count,'rsvp_status',i.rsvp_status) order by i.full_name) filter (where i.id is not null),'[]'::jsonb) as guests
 from reception_tables t left join invitations i on i.table_id=t.id
 where is_admin() group by t.id order by t.name;
$$;

grant execute on function public.admin_list_tables() to authenticated;

create or replace function public.admin_create_table(p_name text,p_capacity integer,p_description text default null)
returns bigint language plpgsql security definer set search_path=public as $$
declare v_id bigint;
begin if not is_admin() then raise exception 'Não autorizado'; end if;
 insert into reception_tables(name,capacity,description) values(trim(p_name),p_capacity,nullif(trim(p_description),'')) returning id into v_id; return v_id; end $$;
grant execute on function public.admin_create_table(text,integer,text) to authenticated;

create or replace function public.admin_update_table(p_id bigint,p_name text,p_capacity integer,p_description text default null)
returns void language plpgsql security definer set search_path=public as $$
