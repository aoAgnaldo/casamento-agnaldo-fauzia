create or replace function public.admin_assign_guest_table(p_invitation_id uuid,p_table_id bigint)
returns void language plpgsql security definer set search_path=public as $$
declare cap integer; used integer;
begin if not is_admin() then raise exception 'Não autorizado'; end if;
 if p_table_id is not null then select capacity into cap from reception_tables where id=p_table_id; if cap is null then raise exception 'Mesa não encontrada'; end if;
 select coalesce(sum(1+coalesce(companion_count,0)),0) into used from invitations where table_id=p_table_id and id<>p_invitation_id and rsvp_status='confirmed';
 if used + coalesce((select 1+coalesce(companion_count,0) from invitations where id=p_invitation_id),1) > cap then raise exception 'A mesa não tem lugares suficientes'; end if; end if;
 update invitations set table_id=p_table_id where id=p_invitation_id;
end $$;
grant execute on function public.admin_assign_guest_table(uuid,bigint) to authenticated;

